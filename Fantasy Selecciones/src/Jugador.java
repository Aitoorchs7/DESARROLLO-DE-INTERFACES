

public class Jugador {
    public String nombre;
    public String seleccion;
    public String pais;
    public String posicion;
    public int precio;
    public int puntos;

    public Jugador(String nombre, String seleccion, String pais, String posicion, int precio, int puntos) {
        this.nombre = nombre;
        this.seleccion = seleccion;
        this.pais = pais;
        this.posicion = posicion;
        this.precio = precio;
        this.puntos = puntos;
    }
}
