

public class Jugador {
    public String nombre;
    public String seleccion;
    public String pais;
    public String posicion;
    public int precio;
    public int puntos;
    public String avatar;
    public String liga;

    public Jugador(String nombre, String seleccion, String pais, String posicion, int precio, int puntos, String avatar, String liga) {
        this.nombre = nombre;
        this.seleccion = seleccion;
        this.pais = pais;
        this.posicion = posicion;
        this.precio = precio;
        this.puntos = puntos;
        this.avatar = avatar;
        this.liga = liga;
    }
}
